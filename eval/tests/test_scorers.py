class TestCsvwAirScore:
    """Row-level AI-readiness: typed half + reference-resolution half."""

    def test_no_pipeline_report_reads_not_assessed(self) -> None:
        graph = _table_graph(compound_value_url=True, cell_line_value_url=True)
        result = condition_table_typing_score(_ref_state(), graph, None)
        assert result["score"] is None
        assert "not assessed" in result["reason"]

    def test_header_only_table_scores_zero(self) -> None:
        # THE anti-tautology guard: full CSVW typing over zero rows is vacuous.
        graph = _table_graph(compound_value_url=True, cell_line_value_url=True)
        record = {"populated": False, "rows": 0, "path": ""}
        result = condition_table_typing_score(_ref_state(), graph, record)
        assert result["score"] == 0.0

    def test_populated_resolving_table_scores_full(self, tmp_path: Path) -> None:
        path = _write_table(
            tmp_path / "t.csv",
            [{"well_id": "1", "cell_line": "CHO-K1", "compound": "Thyroxine"}],
        )
        graph = _table_graph(compound_value_url=True, cell_line_value_url=True)
        record = {"populated": True, "rows": 1, "path": path}
        result = condition_table_typing_score(_ref_state(), graph, record)
        assert result["score"] == 1.0

    def test_dropped_valueurl_on_multivalued_column_is_not_penalised(self, tmp_path: Path) -> None:
        # The #408 rule: two distinct compounds -> compound valueUrl legitimately
        # dropped; both cells still resolve in-crate, so the axis stays 1.0.
        path = _write_table(
            tmp_path / "t.csv",
            [
                {"well_id": "1", "cell_line": "CHO-K1", "compound": "Thyroxine"},
                {"well_id": "2", "cell_line": "CHO-K1", "compound": "Triiodothyronine"},
            ],
        )
        graph = _table_graph(compound_value_url=False, cell_line_value_url=True)
        record = {"populated": True, "rows": 2, "path": path}
        result = condition_table_typing_score(_ref_state(), graph, record)
        assert result["score"] == 1.0

    def test_single_valued_column_missing_valueurl_is_penalised(self, tmp_path: Path) -> None:
        # One distinct compound -> #408 never fired, so a missing valueUrl is a
        # genuine typing gap: the compound column loses its half of the ref score.
        path = _write_table(
            tmp_path / "t.csv",
            [{"well_id": "1", "cell_line": "CHO-K1", "compound": "Thyroxine"}],
        )
        graph = _table_graph(compound_value_url=False, cell_line_value_url=True)
        record = {"populated": True, "rows": 1, "path": path}
        result = condition_table_typing_score(_ref_state(), graph, record)
        assert result["score"] == 0.75

    def test_unresolvable_cell_fails_its_column(self, tmp_path: Path) -> None:
        path = _write_table(
            tmp_path / "t.csv",
            [{"well_id": "1", "cell_line": "CHO-K1", "compound": "Mystery compound"}],
        )
        graph = _table_graph(compound_value_url=True, cell_line_value_url=True)
        record = {"populated": True, "rows": 1, "path": path}
        result = condition_table_typing_score(_ref_state(), graph, record)
        assert result["score"] == 0.75

    def test_unreadable_payload_earns_only_the_typed_half(self, tmp_path: Path) -> None:
        graph = _table_graph(compound_value_url=True, cell_line_value_url=True)
        record = {"populated": True, "rows": 3, "path": str(tmp_path / "missing.csv")}
        result = condition_table_typing_score(_ref_state(), graph, record)
        assert result["score"] == 0.5
        assert "payload" in result["reason"]

    def test_no_table_node_in_graph_scores_zero(self, tmp_path: Path) -> None:
        path = _write_table(
            tmp_path / "t.csv",
            [{"well_id": "1", "cell_line": "CHO-K1", "compound": "Thyroxine"}],
        )
        record = {"populated": True, "rows": 1, "path": path}
        result = condition_table_typing_score(_ref_state(), [], record)
        assert result["score"] == 0.0

    def test_case_mismatched_cell_does_not_resolve(self, tmp_path: Path) -> None:
        # Exact-match semantics, same as the build's Frictionless FK check: a
        # scorer more lenient than the build would inflate the axis on files
        # the build itself flags.
        path = _write_table(
            tmp_path / "t.csv",
            [{"well_id": "1", "cell_line": "CHO-K1", "compound": "THYROXINE"}],
        )
        graph = _table_graph(compound_value_url=True, cell_line_value_url=True)
        record = {"populated": True, "rows": 1, "path": path}
        result = condition_table_typing_score(_ref_state(), graph, record)
        assert result["score"] == 0.75
        assert result["columns"]["compound"]["resolves_in_crate"] is False

    def test_stale_populated_report_over_header_only_file_scores_zero(
        self, tmp_path: Path
    ) -> None:
        # The file, not the self-report, is the row authority: a stale
        # populated=True report over a header-only CSV must not earn the
        # typed half.
        path = _write_table(tmp_path / "t.csv", [])
        graph = _table_graph(compound_value_url=True, cell_line_value_url=True)
        record = {"populated": True, "rows": 3, "path": path}
        result = condition_table_typing_score(_ref_state(), graph, record)
        assert result["score"] == 0.0

    def test_blank_reference_column_is_penalised_and_diagnosable(
        self, tmp_path: Path
    ) -> None:
        # Uniform denominator: a reference column with no cells has no
        # resolving references — it scores 0 with cells=0 in the detail,
        # exactly like any other failing column.
        path = _write_table(
            tmp_path / "t.csv",
            [{"well_id": "1", "cell_line": "CHO-K1", "compound": ""}],
        )
        graph = _table_graph(compound_value_url=True, cell_line_value_url=True)
        record = {"populated": True, "rows": 1, "path": path}
        result = condition_table_typing_score(_ref_state(), graph, record)
        assert result["score"] == 0.75
        assert result["columns"]["compound"]["cells"] == 0

    def test_malformed_csv_degrades_instead_of_raising(self, tmp_path: Path) -> None:
        # A depositor cell with non-UTF-8 bytes raises UnicodeDecodeError, not
        # OSError — it must degrade the axis, never abort a multi-case eval run.
        path = tmp_path / "t.csv"
        path.write_bytes(b"well_id,compound\n1,bad\xff\xfecell\n")
        graph = _table_graph(compound_value_url=True, cell_line_value_url=True)
        record = {"populated": True, "rows": 1, "path": str(path)}
        result = condition_table_typing_score(_ref_state(), graph, record)
        assert result["score"] == 0.5
        assert "payload" in result["reason"]

    def test_report_path_selects_the_populated_table(self, tmp_path: Path) -> None:
        # Multi-Exposure crates carry one table per Exposure but populate only
        # one; the report's path decides which one is being scored. The decoy
        # here has no resolvable schema, so picking it would score 0.
        path = _write_table(
            tmp_path / "exp2_condition_table.csv",
            [{"well_id": "1", "cell_line": "CHO-K1", "compound": "Thyroxine"}],
        )
        decoy = {
            "@id": "data/exp1_condition_table.csv",
            "@type": ["File", "csvw:Table"],
            "name": "AUTOGENERATED — Condition table",
        }
        target_trio = _table_graph(compound_value_url=True, cell_line_value_url=True)
        target_trio[0]["@id"] = "data/exp2_condition_table.csv"
        record = {"populated": True, "rows": 1, "path": path}
        result = condition_table_typing_score(_ref_state(), [decoy, *target_trio], record)
        assert result["score"] == 1.0

    def test_real_emitter_graph_is_matched(self, tmp_path: Path) -> None:
        # Anti-tautology (#343): drive the REAL synthesizer, not the hand-built
        # replica — if _synth_condition_table changes its @id or schema wiring,
        # this test reddens while the replica-based ones stay green.
        from builder.tools.mit_assessment import _assemble_graph
        from tests.fixtures.vhps_golden_crates import vhps_fixture_state

        state = vhps_fixture_state("S-VHPS21")
        graph = _assemble_graph(state)
        table_id = next(
            str(n["@id"])
            for n in graph
            if str(n.get("@id", "")).endswith("_condition_table.csv")
        )
        compound = state.list_entities("MolecularEntity")[0]
        cell = state.list_entities("CellLineSample")[0]
        path = _write_table(
            tmp_path / Path(table_id).name,
            [
                {
                    "well_id": "1",
                    "cell_line": str(cell.fields.get("name") or cell.entity_id),
                    "compound": str(compound.fields.get("name") or compound.entity_id),
                }
            ],
        )
        record = {"populated": True, "rows": 1, "path": path}
        result = condition_table_typing_score(state, graph, record)
        assert result["score"] == 1.0
        assert set(result["columns"]) == {"compound", "cell_line"}
