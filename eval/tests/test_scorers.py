def _iri_params() -> dict[str, str]:
    """Oracle from the spec: every MIT param id -> its curated ontology IRI."""
    data = load_mit_yaml()
    assert data is not None
    out: dict[str, str] = {}
    for module in data.get("modules", []):
        for param in unique_module_params(module):
            iri = param.get("iri")
            if iri:
                out[str(param.get("id"))] = str(iri)
    return out


def _pv(iri: str | dict | None, value: Any, *, node_id: str = "#pv1") -> dict:
    node: dict[str, Any] = {
        "@id": node_id,
        "@type": "PropertyValue",
        "name": "some parameter",
        "value": value,
    }
    if iri is not None:
        node["propertyID"] = iri
    return node


def _ref_state() -> CrateState:
    state = CrateState()
    state.add_entity(
        Entity(
            entity_id="chem_thyroxine",
            type="MolecularEntity",
            fields={"name": "Thyroxine"},
            _provenance=EntityProvenance(created_by="lookup"),
        )
    )
    state.add_entity(
        Entity(
            entity_id="chem_t3",
            type="MolecularEntity",
            fields={"name": "Triiodothyronine"},
            _provenance=EntityProvenance(created_by="lookup"),
        )
    )
    state.add_entity(
        Entity(
            entity_id="cell_cho",
            type="CellLineSample",
            fields={"name": "CHO-K1"},
            _provenance=EntityProvenance(created_by="llm"),
        )
    )
    return state


_HEADER = [
    "well_id",
    "assay",
    "cell_line",
    "compound",
    "concentration_value",
    "concentration_unit",
    "exposure_duration",
    "experiment",
    "technical_replicate",
    "control",
]


def _write_table(path: Path, rows: list[dict[str, str]]) -> str:
    with path.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=_HEADER)
        writer.writeheader()
        for row in rows:
            writer.writerow({k: row.get(k, "") for k in _HEADER})
    return str(path)


def _table_graph(*, compound_value_url: bool, cell_line_value_url: bool) -> list[dict]:
    """The condition-table trio exactly as ``_synth_condition_table`` emits it."""
    columns = []
    for title, value_url in (
        ("well_id", None),
        ("cell_line", "#Sample_cell_cho" if cell_line_value_url else None),
        ("compound", "#chem_thyroxine" if compound_value_url else None),
    ):
        col: dict[str, Any] = {
            "@id": f"#exp_col_{title}",
            "@type": "csvw:Column",
            "titles": title,
            "datatype": "string",
            "propertyUrl": {"@id": f"http://example.org/prop/{title}"},
        }
        if value_url:
            col["valueUrl"] = {"@id": value_url}
        columns.append(col)
    return [
        {
            "@id": "data/LabProcess_exp_condition_table.csv",
            "@type": ["File", "csvw:Table"],
            "name": "AUTOGENERATED — Condition table",
            "tableSchema": {"@id": "#exp_condition_table_schema"},
        },
        {
            "@id": "#exp_condition_table_schema",
            "@type": ["csvw:Schema", "CreativeWork"],
            "name": "Condition table schema",
            "columns": [{"@id": c["@id"]} for c in columns],
        },
        *columns,
    ]


