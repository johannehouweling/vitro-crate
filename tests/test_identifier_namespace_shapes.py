def _crate(nodes: list[dict]) -> dict:
    return {
        "@context": ISA_TOX_CONTEXT,
        "@graph": [
            {"@id": "ro-crate-metadata.json", "@type": "CreativeWork", "about": {"@id": "./"}},
            {
                "@id": "./",
                "@type": "Dataset",
                "additionalType": "Investigation",
                "name": "Identifiers",
                "description": "Well-formed and malformed identifiers.",
                "mentions": [{"@id": n["@id"]} for n in nodes],
            },
            *nodes,
        ],
    }


def _findings(doc: dict, severity: str) -> list[tuple[str, str, str]]:
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        (result,) = validate_crate_dict(doc, severity=severity, profile="tox")
    return [
        ((i.entity_id or "").removeprefix("./"), i.message or "", i.severity)
        for i in result.issues
    ]


_WORDS = (ns.MALFORMED, ns.PERSON_NEEDS_ORCID, ns.ORGANIZATION_NEEDS_ROR)


@pytest.fixture(scope="module")
def required_findings():
    malformed = [{"@id": node_id, **node} for node_id, (node, _) in MALFORMED_NODES.items()]
    return _findings(_crate(WELL_FORMED_OR_NOT_CLAIMED + malformed), "required")


class TestWhatIsReported:
    def test_each_malformed_identifier_draws_its_finding(self, required_findings):
        for node_id, (_, words) in MALFORMED_NODES.items():
            assert any(e == node_id and words in m for e, m, _ in required_findings), (
                node_id,
                [f for f in required_findings if f[0] == node_id],
            )

    def test_each_is_reported_once(self, required_findings):
        reported = [e for e, m, _ in required_findings if any(w in m for w in _WORDS)]
        assert sorted(reported) == sorted(MALFORMED_NODES)

    def test_nothing_well_formed_or_unclaimed_is_reported(self, required_findings):
        reported = {e for e, m, _ in required_findings if any(w in m for w in _WORDS)}
        assert reported == set(MALFORMED_NODES), sorted(reported ^ set(MALFORMED_NODES))

    def test_a_malformed_identifier_is_a_violation(self, required_findings):
        assert {s for _, m, s in required_findings if any(w in m for w in _WORDS)} == {"required"}

    def test_a_node_level_finding_names_no_property(self):
        """The @id itself is wrong; there is no field to fill."""
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            (result,) = validate_crate_dict(
                _crate([{"@id": f"{OBO}NCIT_16403", "@type": "DefinedTerm", "name": "x"}]),
                severity="required",
                profile="tox",
            )
        node_level = [i for i in result.issues if ns.MALFORMED in (i.message or "")]
        assert node_level and all(i.property is None for i in node_level)


class TestTheCellLineAccession:
    """SHOULD: a cell line carries its Cellosaurus accession, in any of its forms."""

    CELL_LINE = {"@id": f"{OBO}NCIT_C16403"}

    def _line(self, node_id: str, identifier=None) -> dict:
        node = {"@id": node_id, "@type": "Sample", "name": node_id, "sampleType": self.CELL_LINE}
        if identifier is not None:
            node["identifier"] = identifier
        return node

    def test_only_an_accession_counts(self):
        nodes = [
            _term(f"{OBO}NCIT_C16403"),
            self._line("#plain", "CVCL_0440"),
            self._line("#rrid", "RRID:CVCL_0440"),
            self._line("#address", {"@id": "https://www.cellosaurus.org/CVCL_0440"}),
            self._line("#value", {"@id": "#pv-accession"}),
            _value("#pv-accession", "Cellosaurus", "CVCL_0440"),
            self._line("#a-name", "HeLa"),
            self._line("#none"),
        ]
        warned = {
            e
            for e, m, s in _findings(_crate(nodes), "recommended")
            if "Cellosaurus accession" in m and s == "recommended"
        }
        assert warned == {"#a-name", "#none"}


class TestAFunderNamedOnlyAsOne:
    """A funding programme has no ROR record, so a funder's ROR ID is a SHOULD."""

    def _crate(self) -> dict:
        nodes = [
            {"@id": "#programme", "@type": "Organization", "name": "EU Horizon 2020"},
            {"@id": "#both", "@type": "Organization", "name": "A lab"},
            {"@id": "#lab", "@type": "Organization", "name": "An unreferenced lab"},
            {"@id": "https://ror.org/04jsz6e67", "@type": "Organization", "name": "NWO"},
            {"@id": "#grant", "@type": "Grant", "name": "g", "funder": {"@id": "#programme"}},
            {
                "@id": "https://orcid.org/0000-0002-1825-0097",
                "@type": "Person",
                "name": "Josiah Carberry",
                "affiliation": {"@id": "#both"},
            },
        ]
        doc = _crate(nodes)
        root = doc["@graph"][1]
        root.pop("mentions")
        root["funder"] = [{"@id": "#programme"}, {"@id": "#both"}, {"@id": "https://ror.org/04jsz6e67"}]
        root["funding"] = {"@id": "#grant"}
        return doc

    def _ror(self, severity: str) -> set[tuple[str, str]]:
        return {
            (e, s)
            for e, m, s in _findings(self._crate(), severity)
            if "identified by a ROR ID" in m
        }

    def test_only_a_funder_is_recommended_and_everything_else_required(self):
        assert self._ror("recommended") == {
            ("#programme", "recommended"),
            ("#both", "required"),
            ("#lab", "required"),
        }

    def test_the_required_gate_does_not_see_the_funder(self):
        assert self._ror("required") == {("#both", "required"), ("#lab", "required")}
