class TestLocalScopeIsHonest:
    """What we assess is declared per indicator, and never inflated."""

    def test_every_scoped_indicator_names_a_registered_check(self):
        from builder.tools.fair_assessment import DSM_CHECKS

        for ind in _yaml()["indicators"]:
            if ind["scope"] == "na":
                assert "check" not in ind, f"{ind['id']} is na but names a check"
                continue
            assert ind.get("check") in DSM_CHECKS, (
                f"{ind['id']} is scoped {ind['scope']!r} but its check "
                f"{ind.get('check')!r} is not registered in DSM_CHECKS"
            )

    def test_hosting_indicators_are_never_claimed_as_assessable(self):
        """A crate on disk cannot evidence its hosting environment's capabilities."""
        for ind in _yaml()["indicators"]:
            if ind["category"] == "H":
                assert ind["scope"] == "na", f"{ind['id']} is a hosting indicator"

    def test_level_zero_is_never_scored(self):
        """Level 0 states the pre-FAIR condition in the negative; passing it is bad."""
        for ind in _yaml()["indicators"]:
            if ind["level"] == 0:
                assert ind["scope"] == "na", f"{ind['id']} is a Level-0 negative state"

    def test_the_model_s_own_rda_cross_references_are_carried(self):
        """27 indicators cite an RDA indicator — the published bridge between the axes."""
        linked = [i for i in _yaml()["indicators"] if i.get("rda_ref")]
        assert len(linked) == 27
        assert all(i["rda_ref"].startswith(("RDA-", "[")) for i in linked)


