"""The DSM indicators are DERIVED from the vendored FAIRplus assessment workbook
(``fair/fairplus_dsm_v1.2.xlsx``), not hand-authored.

``fair/dsm_indicators.yaml`` is generated by ``scripts/gen_dsm_indicators.py`` from the
workbook's "MASTER (Levels View)" sheet (definitions: level / category / verbatim text /
granularity / the model's own RDA + FAIRsFAIR cross-references) plus a local scope/check
map. These tests pin that contract so the published model can never silently drift into a
paraphrase, and so the paper's claim to be scoring *the FAIRplus DSM* stays true.

The prior hand-curated file carried 28 entries — 25 of the 83 published indicators, one
invented id (``DSM-5``), paraphrased text, and level names found nowhere in the model.
"""

from __future__ import annotations

import importlib.util
import pathlib

import openpyxl
import yaml

REPO = pathlib.Path(__file__).resolve().parents[1]
DSM_YAML = REPO / "fair" / "dsm_indicators.yaml"
DSM_XLSX = REPO / "fair" / "fairplus_dsm_v1.2.xlsx"
GEN = REPO / "scripts" / "gen_dsm_indicators.py"

# The published model, as distributed in v1.2 of the assessment sheet.
PUBLISHED_TOTAL = 83
PUBLISHED_PER_LEVEL = {0: 11, 1: 14, 2: 15, 3: 16, 4: 14, 5: 13}
PUBLISHED_PER_CATEGORY = {"C": 31, "R": 32, "H": 20}


def _load_generator():
    spec = importlib.util.spec_from_file_location("gen_dsm_indicators", GEN)
    assert spec and spec.loader
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _yaml() -> dict:
    return yaml.safe_load(DSM_YAML.read_text())


def _workbook_rows() -> dict[str, dict]:
    """Indicator id -> row, read straight from the vendored workbook."""
    wb = openpyxl.load_workbook(DSM_XLSX, read_only=True, data_only=True)
    ws = wb["MASTER (Levels View)"]
    out: dict[str, dict] = {}
    level = None
    for row in list(ws.iter_rows(values_only=True))[1:]:
        if row[0] not in (None, ""):
            try:
                level = int(float(row[0]))
            except (TypeError, ValueError):
                pass
        ident = str(row[2]).strip() if row[2] else ""
        if not ident.startswith("DSM-"):
            continue
        out[ident] = {
            "level": level,
            "text": str(row[4]).strip() if row[4] else "",
            "granularity": str(row[7]).strip() if row[7] else "",
        }
    return out


class TestGeneratedFromTheWorkbook:
    """The committed YAML is exactly what the generator produces from the workbook."""

    def test_committed_yaml_equals_generator_output(self):
        mod = _load_generator()
        assert _yaml() == mod.build_data(), (
            "fair/dsm_indicators.yaml is stale or hand-edited — "
            "regenerate with `uv run python scripts/gen_dsm_indicators.py`"
        )

    def test_the_vendored_workbook_is_present(self):
        assert DSM_XLSX.is_file() and DSM_XLSX.stat().st_size > 100_000


class TestTheWholePublishedModelIsCarried:
    """All 83 indicators, not the subset we happen to assess."""

    def test_every_published_indicator_is_present(self):
        ids = {i["id"] for i in _yaml()["indicators"]}
        assert ids == set(_workbook_rows())
        assert len(ids) == PUBLISHED_TOTAL

    def test_counts_per_level_and_category(self):
        inds = _yaml()["indicators"]
        per_level: dict[int, int] = {}
        per_cat: dict[str, int] = {}
        for i in inds:
            per_level[i["level"]] = per_level.get(i["level"], 0) + 1
            per_cat[i["category"]] = per_cat.get(i["category"], 0) + 1
        assert per_level == PUBLISHED_PER_LEVEL
        assert per_cat == PUBLISHED_PER_CATEGORY

    def test_indicator_text_is_verbatim_never_paraphrased(self):
        rows = _workbook_rows()
        for ind in _yaml()["indicators"]:
            src = rows[ind["id"]]
            assert ind["text"] == src["text"], f"{ind['id']} text drifted from the model"
            assert ind["level"] == src["level"], f"{ind['id']} level drifted"
            assert ind["granularity"] == src["granularity"], f"{ind['id']} granularity drifted"

    def test_no_invented_identifiers_survive(self):
        """The old file carried a bare ``DSM-5`` placeholder that the model never defined."""
        ids = {i["id"] for i in _yaml()["indicators"]}
        assert "DSM-5" not in ids
        # Every id is <model>-<level>-<category><n>, so a bare level id cannot recur.
        for iid in ids:
            assert iid.count("-") >= 2, f"{iid} is not a published DSM identifier"


