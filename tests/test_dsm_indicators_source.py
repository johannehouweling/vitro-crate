class TestTheModelsOwnPercentCompleteGrid:
    """`dsm_grid` reproduces the assessment sheet's 6x3 "% Complete" scoring.

    The sheet's formula, verbatim from cell P10 (Level 1, Content and context)::

        =(((COUNTIFS(J32,1))+(COUNTIFS(J45,1))+(COUNTIFS(J50,1))+(COUNTIFS(J51,1)))
          /(COUNT(J32,J45,J50,J51))*100)

    and P6 (Level 0), which counts ZEROS rather than ones::

        =(((COUNTIFS(J31,0))+(COUNTIFS(J44,0))+(COUNTIFS(J49,0)))/(COUNT(J31,J44,J49))*100)
    """

    def _grid(self):
        from builder.tools.fair_assessment import dsm_grid
        from tests.fixtures.vhps_golden_crates import vhps_fixture_state

        return dsm_grid(vhps_fixture_state("S-VHPS21"))

    def test_the_grid_covers_every_published_level_and_category(self):
        grid = self._grid()
        assert set(grid) == set(PUBLISHED_PER_LEVEL)
        for level, by_cat in grid.items():
            assert set(by_cat) <= {"C", "R", "H"}, level
            assert sum(c["total"] for c in by_cat.values()) == PUBLISHED_PER_LEVEL[level]

    def test_percentage_is_over_what_was_assessed_not_what_exists(self):
        """The sheet's denominator is Excel COUNT, which omits unanswered cells.

        An indicator we cannot assess is an unanswered cell: it must not count
        against the dataset, or every percentage would be diluted by the 20
        hosting indicators no crate can ever evidence.
        """
        for by_cat in self._grid().values():
            for cell in by_cat.values():
                assert cell["assessed"] <= cell["total"]
                if cell["assessed"]:
                    expected = round(cell["passed"] / cell["assessed"] * 100, 1)
                    assert cell["pct"] == expected
                    assert cell["passed"] <= cell["assessed"]

    def test_an_unassessable_cell_is_none_never_zero(self):
        """`#DIV/0!` in the sheet — "not assessed" is not the same claim as 0%."""
        grid = self._grid()
        for level in (0, 5):
            for cell in grid[level].values():
                assert cell["assessed"] == 0
                assert cell["pct"] is None
        for by_cat in grid.values():
            hosting = by_cat.get("H")
            if hosting:
                assert hosting["pct"] is None, "no crate can evidence its hosting environment"

    def test_level_zero_is_scored_inverted(self):
        """Level 0 counts ZEROS (P6). Satisfying "data is NOT identifiable" is bad.

        Driven through the real scorer rather than asserted structurally: a
        level-0 indicator wired to a check that PASSES must score 0 there, which
        is the opposite of every other level.
        """
        from builder.tools import fair_assessment as fa
        from tests.fixtures.vhps_golden_crates import vhps_fixture_state

        data = {
            "indicators": [
                {"id": "DSM-0-C0", "level": 0, "category": "C",
                 "scope": "full", "check": "unique_id"},
                {"id": "DSM-1-C0", "level": 1, "category": "C",
                 "scope": "full", "check": "unique_id"},
            ]
        }
        state = vhps_fixture_state("S-VHPS21")
        assert fa.DSM_CHECKS["unique_id"](state, None) is True
        grid = fa.dsm_grid(state, data)
        assert grid[0]["C"]["passed"] == 0, "a satisfied Level-0 negative must not score"
        assert grid[1]["C"]["passed"] == 1, "the same check at Level 1 must score"

    def test_the_report_renders_the_grid_faithfully(self):
        from builder.writers.maturity_report import build_maturity_html
        from tests.fixtures.vhps_golden_crates import vhps_fixture_state

        page = build_maturity_html(vhps_fixture_state("S-VHPS21"))
        assert "DSM &mdash; % complete by level and category" in page
        # Every published level name is a row label.
        for name in _yaml()["levels"].values():
            assert name in page
        # An unassessable cell says so rather than showing a zero.
        assert "not assessed" in page
        # The deviation from the sheet is stated, not implied.
        assert "excluded from the denominator" in page
        assert "scored inverted" in page


class TestNoGraphMeansUnanswered:
    """A graph-aware check with no graph answers ``None``, never ``False``.

    The DSM's Level 2-4 field/value indicators live in the assembled ``@graph``.
    Answering ``False`` when no graph was supplied would read as "the crate fails
    this indicator" when the truth is "nothing was assessed" — and it would drag the
    gated level down on every caller that scores from ``CrateState`` alone.
    """

    def _state(self):
        from tests.fixtures.vhps_golden_crates import vhps_fixture_state

        return vhps_fixture_state("S-VHPS21")

    def test_graph_checks_return_none_without_a_graph(self):
        from builder.tools.fair_assessment import DSM_CHECKS

        graph_aware = [
            "tidy_dataset", "reference_fields", "local_data_dictionary",
            "local_dataset_model", "standard_field_names", "non_proprietary_format",
            "semantic_contextual_metadata", "common_data_elements",
        ]
        for name in graph_aware:
            assert DSM_CHECKS[name](self._state(), None) is None, name

    def test_an_unanswered_indicator_leaves_the_denominator(self):
        from builder.tools.fair_assessment import dsm_grid

        state = self._state()
        without = dsm_grid(state, None, None)
        # With no graph, the field/value indicators are unanswered, so the
        # denominator shrinks — it must never grow a failure instead.
        for level, by_cat in without.items():
            for cat, cell in by_cat.items():
                assert cell["passed"] <= cell["assessed"], (level, cat)

    def test_the_gated_level_is_not_dragged_down_by_a_missing_graph(self):
        """The regression this guards: scoring from CrateState alone must not fall."""
        from builder.tools.fair_assessment import assess_fair_maturity

        assert assess_fair_maturity(self._state()).dsm_level == 2


class TestTheQuestionnaireLadder:
    """The instrument is 18 multiple-choice questions whose options nest by level.

    Within one question the statements form a ladder — "standardised to a *community*
    Standard Dataset Model" (L3) sits above "...to a *locally defined* Dataset Model"
    (L2) — so an option cannot honestly be true while a lower rung of the same
    question is false. Scoring indicators independently can produce exactly that
    incoherence, so the scorer demotes rather than publishing it.
    """

    def test_the_questionnaire_is_carried(self):
        data = _yaml()
        questions = data["questions"]
        assert len(questions) == 18
        assert sum(len(q["options"]) for q in questions) == 73
        assert any(q["multi_select"] for q in questions)

    def test_option_levels_agree_with_the_master_sheet(self):
        """The questionnaire's own LEVEL cell is multi-valued ("Level 1, Level 2"),
        so it cannot order a ladder; the MASTER sheet is authoritative."""
        data = _yaml()
        levels = {i["id"]: i["level"] for i in data["indicators"]}
        for question in data["questions"]:
            for option in question["options"]:
                assert option["level"] == levels[option["id"]], option["id"]

    def test_a_failed_rung_demotes_the_rungs_above_it(self):
        from builder.tools import fair_assessment as fa

        data = {
            "indicators": [
                {"id": "A", "level": 2, "category": "C", "scope": "full", "check": "no"},
                {"id": "B", "level": 3, "category": "C", "scope": "full", "check": "yes"},
            ],
            "questions": [
                {"question": "q", "options": [{"id": "A", "level": 2}, {"id": "B", "level": 3}]}
            ],
        }
        checks = {"no": lambda _s, _g=None: False, "yes": lambda _s, _g=None: True}
        import unittest.mock as m

        with m.patch.dict(fa.DSM_CHECKS, checks):
            verdicts = fa.dsm_verdicts(CrateStateStub(), data, None)
        assert verdicts["A"].value is False
        assert verdicts["B"].value is False, "a higher rung must not stand on a failed one"
        assert "demoted" in verdicts["B"].evidence
        assert "A" in verdicts["B"].evidence, "the evidence must name what blocked it"

    def test_siblings_at_the_same_level_do_not_demote_each_other(self):
        """The ladder runs ACROSS levels. Two options at the same level are
        independent statements, so one failing must not drag the other down."""
        from builder.tools import fair_assessment as fa

        data = {
            "indicators": [
                {"id": "A", "level": 1, "category": "C", "scope": "full", "check": "no"},
                {"id": "B", "level": 1, "category": "C", "scope": "full", "check": "yes"},
            ],
            "questions": [
                {"question": "q", "options": [{"id": "A", "level": 1}, {"id": "B", "level": 1}]}
            ],
        }
        checks = {"no": lambda _s, _g=None: False, "yes": lambda _s, _g=None: True}
        import unittest.mock as m

        with m.patch.dict(fa.DSM_CHECKS, checks):
            verdicts = fa.dsm_verdicts(CrateStateStub(), data, None)
        assert verdicts["B"].value is True

    def test_an_unanswered_rung_neither_blocks_nor_is_blocked(self):
        from builder.tools import fair_assessment as fa

        data = {
            "indicators": [
                {"id": "A", "level": 2, "category": "C", "scope": "full", "check": "none"},
                {"id": "B", "level": 3, "category": "C", "scope": "full", "check": "yes"},
            ],
            "questions": [
                {"question": "q", "options": [{"id": "A", "level": 2}, {"id": "B", "level": 3}]}
            ],
        }
        checks = {"none": lambda _s, _g=None: None, "yes": lambda _s, _g=None: True}
        import unittest.mock as m

        with m.patch.dict(fa.DSM_CHECKS, checks):
            verdicts = fa.dsm_verdicts(CrateStateStub(), data, None)
        assert verdicts["A"].value is None
        assert verdicts["B"].value is True, "absent evidence is not a failed rung"


class TestEveryVerdictCarriesItsEvidence:
    """A bare boolean cannot be audited; the model is a human assessment instrument."""

    def test_graph_checks_report_what_they_measured(self):
        import json

        from builder.tools.fair_assessment import dsm_verdicts

        crate = REPO / "output" / "svhps22_real_input_crate_v20" / "ro-crate-metadata.json"
        if not crate.is_file():
            import pytest

            pytest.skip("no built crate on disk to score")
        graph = json.loads(crate.read_text())["@graph"]
        verdicts = dsm_verdicts(CrateStateStub(), None, graph)
        measured = [v for v in verdicts.values() if v.evidence]
        assert measured, "no verdict carried evidence"
        # Evidence must be a measurement, not a restatement of the verdict.
        joined = " ".join(v.evidence for v in measured)
        assert any(ch.isdigit() for ch in joined), "evidence should quantify what was found"

    def test_verdict_refuses_truthiness(self):
        """Tri-state: `if verdict:` must not silently read None as False."""
        import pytest

        from builder.tools.fair_assessment import Verdict

        with pytest.raises(TypeError, match="tri-state"):
            bool(Verdict(None, ""))


