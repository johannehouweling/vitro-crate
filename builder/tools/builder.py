"""Tool that assembles an RO-Crate directory from CrateState entity data.

The crate is assembled with `ro-crate-py` (the official RO-Crate SDK): a
`ROCrate` is created, the ISA-Tox JSON-LD context is attached, and the entity
graph is built by `builder/tools/_crate_mapping.py` (which maps each CrateState
entity onto its ISA-Tox domain-model class, resolves cross-entity references, and
wires the Investigation → Study → Assay → LabProcess graph). `crate.write()` then
serialises a valid `ro-crate-metadata.json`.
"""

from __future__ import annotations

import logging
import os
from pathlib import Path
from typing import Any

from rocrate.model import File
from rocrate.rocrate import ROCrate

import builder.config as _config
from builder.state import CrateState
from builder.tools._crate_mapping import (
    AUTOGENERATED_MARKER,
    populate_crate,
)
from builder.tools.rehome import rehome_misplaced_fields
from profiles.context import ISA_TOX_CONTEXT

logger = logging.getLogger(__name__)

# The placeholder root name ro-crate-py / _crate_mapping fall back to when the
# session has no title. ro-crate-py's bundled preview renders this verbatim as the
# page header, so an untitled crate shows a meaningless "Untitled Investigation"
# (#272). _apply_root_name replaces it with the Investigation/Study name.
# Opt in to the self-contained style: describe every externally-referenced
# vocabulary term as a node in the crate. Off by default — see assemble_crate.
_DESCRIBE_EXTERNAL_TERMS_ENV = "VITRO_DESCRIBE_EXTERNAL_TERMS"

_PLACEHOLDER_ROOT_NAME = "Untitled Investigation"
# The placeholder root description _crate_mapping falls back to when the session
# has neither a description nor a title. Treated as a placeholder so the
# Investigation/Study description (or name) can replace it (#272).
_PLACEHOLDER_ROOT_DESCRIPTION = "RO-Crate generated by vitro-crate."
# Final fallback when neither a session title nor an Investigation/Study name is
# available — still meaningful, never the bare placeholder.
_DEFAULT_ROOT_NAME = "ISA-Tox RO-Crate"


def _first_named(state: CrateState, entity_type: str) -> str | None:
    """The ``name`` of the first entity of *entity_type* with a non-empty name."""
    for entity in state.list_entities(entity_type):
        name = entity.fields.get("name")
        if isinstance(name, str) and name.strip():
            return name.strip()
    return None


def _first_field_value(state: CrateState, entity_type: str, field: str) -> str | None:
    """The first non-empty string *field* across entities of *entity_type*."""
    for entity in state.list_entities(entity_type):
        value = entity.fields.get(field)
        if isinstance(value, str) and value.strip():
            return value.strip()
    return None


def _apply_root_name(crate: ROCrate, state: CrateState) -> None:
    """Give the crate root (``./``) a meaningful name/description for the preview.

    ro-crate-py's bundled preview template (rendered via ``_SafePreview``, #169)
    uses the Root Data Entity ``name`` as the page header. When the session has no
    title, ``_crate_mapping`` leaves the placeholder ``"Untitled Investigation"``
    there, so the preview reads as untitled (#272). This derives a better name —
    and description — from the crate's own ISA backbone and sets it through the
    ro-crate-py API (``crate.root_dataset``):

    1. Investigation ``name`` (the ISA root is the Investigation),
    2. else the first Study ``name``,
    3. else a sensible default (never the bare placeholder).

    A session-level title (``state.metadata.title``) still wins: it is applied
    earlier in assembly, so the root name is already non-placeholder and is left
    untouched. The derivation is deterministic from state, so the graph hash is
    unaffected.
    """
    current = crate.root_dataset.get("name")
    if isinstance(current, str) and current.strip() and current != _PLACEHOLDER_ROOT_NAME:
        return  # An explicit session title (or folded Investigation name) already set it.

    name = (
        _first_named(state, "Investigation") or _first_named(state, "Study") or _DEFAULT_ROOT_NAME
    )
    crate.root_dataset["name"] = name

    current_desc = crate.root_dataset.get("description")
    # The placeholder description mirrors the (placeholder) name or is the generic
    # default (see _crate_mapping), so refresh it whenever it is empty or still a
    # placeholder rather than a real Investigation/Study description.
    if not (isinstance(current_desc, str) and current_desc.strip()) or current_desc in (
        _PLACEHOLDER_ROOT_NAME,
        _PLACEHOLDER_ROOT_DESCRIPTION,
        current,
    ):
        description = (
            _first_field_value(state, "Investigation", "description")
            or _first_field_value(state, "Study", "description")
            or name
        )
        crate.root_dataset["description"] = description


def _default_crate_path(state: CrateState) -> str:
    """Return a session-derived default crate path.

    The convention is ``sessions/<session_id>/working_crate/``, which matches
    the session persistence layout described in AGENTS.md.
    """
    session_id = state.session_id or "unknown"
    return str(_config.session_root() / session_id / "working_crate")


def assemble_crate(
    state: CrateState,
    output_dir: Path | None = None,
    *,
    materialize_payload: bool = True,
    include_all_scanned: bool = True,
) -> ROCrate:
    """Assemble an in-memory `ROCrate` from CrateState — no disk write.

    This is the shared assembly step behind both :func:`export_crate` (which
    then writes the crate to disk) and ``build_and_validate`` (which generates
    the metadata document and validates it in memory). Splitting it out keeps
    disk writes confined to :func:`export_crate`.

    Args:
        state: The CrateState to build from.
        output_dir: Crate root, used only when payload is materialised. ``None``
            for the pure in-memory path.
        materialize_payload: When False, no payload file is written (see
            :func:`builder.tools._crate_mapping.populate_crate`).
        include_all_scanned: When True (default), every file in
            ``state.scanned_files`` that is not already a drafted ``File`` entity
            is auto-included as a ``File`` leaf, so the crate packages the whole
            dataset (#175). The in-memory ``build_and_validate`` path passes
            False — plain leaves don't change the validation verdict and skipping
            them keeps the ReAct loop fast.

    Returns:
        A populated :class:`ROCrate`. Nothing is written unless the caller
        invokes ``crate.write()``.
    """
    # Before anything is composed: move a field written on an entity that cannot
    # hold it to the one that consumes it. `_scalar_props` would otherwise DELETE
    # it — correct for a key the model invented, wrong for a field this codebase
    # asks for by name and then files under the wrong type. Twelve such values
    # (instrument, manufacturer, measured entity, replicate count, across three
    # assays) were deleted from one real build, and the report went on to raise
    # "say which measurement technique was used" about their absence.
    #
    # Mutates `state`, deliberately: the crate is built from state on every
    # export, so rescuing the value only for this build would let the next one
    # delete it again. Never raises — a rescue that breaks the build is worse
    # than the deletion it prevents.
    try:
        rehomed = rehome_misplaced_fields(state)
    except Exception:  # noqa: BLE001 — a rescue must never sink an export
        logger.warning("Could not re-home misplaced fields; continuing", exc_info=True)
        rehomed = []
    for move in rehomed:
        logger.info(
            "Kept %r by moving it from %s to %s, which is the type that consumes it",
            move.field,
            move.from_id,
            move.to_id,
        )

    crate = ROCrate()
    crate.metadata.extra_contexts = ISA_TOX_CONTEXT
    populate_crate(
        state,
        crate,
        output_dir,
        materialize_payload=materialize_payload,
        include_all_scanned=include_all_scanned,
    )
    # Give the root (./) a meaningful name/description from the Investigation
    # (fallback Study, then a default) so ro-crate-py's preview header isn't
    # "Untitled Investigation" (#272).
    _apply_root_name(crate, state)
    # A vocabulary term the crate POINTS AT stays external. `propertyID:
    # BAO_0000114` links to a definition that dereferences and is maintained by
    # its ontology; copying the label in duplicates someone else's data, goes
    # stale on their next release, and adds a node per distinct term for
    # information a reader can already fetch. The crate DESCRIBES what it
    # asserts — its samples, processes, people — and LINKS what it cites.
    #
    # The validator RECOMMENDS the opposite (it wants a self-contained graph),
    # so this costs ~60-76 non-blocking findings per crate and saves ~20 nodes.
    # Deliberate trade: `describe_external_references` still implements the
    # self-contained style for anyone who wants it, and is called by nothing.
    if os.environ.get(_DESCRIBE_EXTERNAL_TERMS_ENV, "").strip().lower() in ("1", "true", "yes"):
        describe_external_references(crate)
    add_schema_org_types(crate)
    return crate


# Properties whose value is an ontology term the crate points AT rather than
# describes. Each is a place where a bare {"@id": <IRI>} is emitted today.
_TERM_REFERENCE_PROPERTIES: tuple[str, ...] = (
    "propertyID",
    "propertyUrl",
    "inDefinedTermSet",
    "conformsTo",
)

# IRIs whose name must NOT be taken from whatever referenced them: a term set,
# a spec, or a generic vocabulary property that many different columns reuse.
# `dcterms:identifier` referenced by a "well_id" column is not called "well_id".
_TERM_SET_NAMES: dict[str, str] = {
    "http://purl.obolibrary.org/obo/ncit.owl": "NCI Thesaurus",
    "https://w3id.org/ro/crate/1.2": "RO-Crate 1.2",
    "http://purl.org/dc/terms/identifier": "identifier",
    "http://purl.org/dc/terms/title": "title",
    "http://purl.org/dc/terms/description": "description",
}


def _label_key(label: str) -> str:
    """A label reduced to what it MEANS, ignoring how it was written."""
    return " ".join(str(label).replace("_", " ").replace("-", " ").lower().split())


def _preferred_label(labels: set[str]) -> str:
    """The most human-readable spelling of one label — the one a person wrote.

    Prefers a variant with spaces over one with underscores, then a longer one,
    then alphabetical so the choice is stable across builds.
    """
    return sorted(labels, key=lambda s: ("_" in s, -len(s), s))[0]


def describe_external_references(crate: ROCrate) -> int:
    """Give every externally-referenced ontology IRI a node that names it.

    An IRI referenced as a bare ``{"@id": …}`` and described nowhere trips three
    RECOMMENDED checks at once — no name, no schema.org type, not present in the
    ``@graph`` — and one real crate collected 143 findings from 22 such IRIs.

    No lookup is needed, which is the point: the label is always sitting on the
    node doing the referencing. ``#param_Culture_Medium`` carries
    ``propertyID: BAO_0000114`` and the name "Culture Medium"; a CSVW column
    carries ``propertyUrl`` and its own ``name``. The term set is what we assert
    the parameter MEANS, so the parameter's own label is the honest name for it
    — this states a relationship the crate already claims, it does not invent
    one. Where no label is in reach the IRI is left alone rather than named
    after its opaque local part ("IAO_0000039" is not a name).

    Idempotent: an IRI that already has an entity is skipped, so re-running over
    an assembled crate changes nothing.

    Returns:
        How many describing entities were added.
    """
    from rocrate.model.contextentity import ContextEntity

    candidates: dict[str, set[str]] = {}
    for entity in list(crate.get_entities()):
        try:
            properties = entity.properties()
        except Exception:  # noqa: BLE001 — a description pass never fails a build
            continue
        label = properties.get("name") or properties.get("titles")
        if isinstance(label, list):
            label = next((x for x in label if isinstance(x, str) and x.strip()), None)
        if not isinstance(label, str) or not label.strip():
            continue
        for prop in _TERM_REFERENCE_PROPERTIES:
            value = properties.get(prop)
            for item in value if isinstance(value, list) else [value]:
                iri = item.get("@id") if isinstance(item, dict) else item
                if isinstance(iri, str) and "://" in iri:
                    candidates.setdefault(iri, set()).add(label.strip())

    labels: dict[str, str] = {}
    for iri, found in candidates.items():
        known = _TERM_SET_NAMES.get(iri)
        if known:
            labels[iri] = known
            continue
        # "Technical replicate" and "technical_replicate" are the same label in
        # two spellings — one written for a person, one for a column header —
        # and refusing to name the term over that is over-caution, not care.
        # Compare with case and separators normalised; a genuine disagreement
        # (two columns using one unit term for different quantities) still
        # differs after normalising and is still left alone.
        if len({_label_key(label) for label in found}) == 1:
            labels[iri] = _preferred_label(found)
        # Disagreement means the referrers are naming their own column, not the
        # term: 'concentration_unit' and 'measured_unit' both point at IAO_0000039
        # (unit of measurement) and neither is its name. Say nothing rather than
        # pick one — an undescribed term is a lesser fault than a mislabelled one.
    labels.update({k: v for k, v in _TERM_SET_NAMES.items() if k in candidates})

    added = 0
    for iri, name in labels.items():
        if crate.dereference(iri) is not None:
            continue
        crate.add(ContextEntity(crate, iri, properties={"@type": "DefinedTerm", "name": name}))
        added += 1
    if added:
        logger.info("Described %d externally-referenced ontology term(s)", added)
    return added


def add_schema_org_types(crate: ROCrate) -> int:
    """Give each domain-typed node its published schema.org supertype as well.

    RO-Crate RECOMMENDS every entity carry a type in the schema.org namespace,
    and the shape enforcing it is syntactic — it looks for a type IRI starting
    with ``http(s)://schema.org/``. Our domain types resolve to
    ``https://bioschemas.org/…``, so a perfectly well-typed LabProcess fails it.

    The supertype is READ from the vendored vocabulary
    (:mod:`profiles.vocabulary`), never decided here. It is a published fact —
    Bioschemas states ``LabProcess rdfs:subClassOf schema:Action`` — and writing
    it out by hand got two of three wrong the first time. A type absent from the
    vocabulary gains nothing: an unfixed RECOMMENDED finding is a smaller harm
    than a fabricated claim about what an entity is.

    The domain type stays FIRST — it is the specific, meaningful one; the
    schema.org term is the general one a generic consumer can follow. Idempotent.

    Returns:
        How many entities gained a type.
    """
    from profiles.vocabulary import type_supertypes

    supertypes = type_supertypes()
    if not supertypes:
        return 0

    updated = 0
    for entity in list(crate.get_entities()):
        try:
            current = entity.type
        except Exception:  # noqa: BLE001 — typing never fails a build
            continue
        types = [str(t) for t in (current if isinstance(current, list) else [current]) if t]
        if any(t.startswith("schema:") or t in _SCHEMA_ORG_TYPE_TOKENS for t in types):
            continue
        companion = next((supertypes[t] for t in types if t in supertypes), None)
        if companion is None or companion in types:
            continue
        # ro-crate-py guards `entity["@type"] = …`, so write the backing JSON-LD.
        entity._jsonld["@type"] = types + [companion]
        updated += 1
    if updated:
        logger.info("Added a published schema.org supertype to %d entit(ies)", updated)
    return updated


# Type tokens the crate context already maps into the schema.org namespace, so a
# node carrying one needs no companion.
_SCHEMA_ORG_TYPE_TOKENS: frozenset[str] = frozenset(
    {
        "Dataset",
        "File",
        "MediaObject",
        "CreativeWork",
        "PropertyValue",
        "DefinedTerm",
        "Person",
        "Organization",
        "ScholarlyArticle",
        "SoftwareApplication",
        "Action",
        "HowTo",
        "Thing",
    }
)




def _add_safe_preview(crate: ROCrate) -> None:
    """Add an XSS-safe ``ro-crate-preview.html`` to *crate* (#169).

    ro-crate-py's bundled :class:`~rocrate.model.preview.Preview` renders its
    HTML through a Jinja2 ``Template`` with autoescaping OFF, so crate-controlled
    strings (the crate ``name``/``description``, every entity ``@id``/``@type``)
    are interpolated raw. A crate whose name is ``<script>…</script>`` therefore
    yields a preview that executes when opened — stored XSS.

    We subclass the bundled ``Preview`` and re-render its *own* vendored template
    through a Jinja2 environment with ``autoescape=True``, so every ``{{ … }}``
    is HTML-escaped (tags become inert text, attribute values can't break out).
    The metadata graph is untouched — escaping is presentation-layer only, so
    ``ro-crate-metadata.json`` keeps the original literal values.
    """
    import os

    from jinja2 import Environment, select_autoescape
    from rocrate.model.preview import Preview

    class _SafePreview(Preview):
        def generate_html(self) -> str:  # type: ignore[override]
            # Locate the vendored template relative to the Preview module so we
            # render exactly what ro-crate-py ships, just with autoescaping on.
            import rocrate.model.preview as _preview_mod

            tpl_dir = os.path.join(
                os.path.dirname(os.path.abspath(_preview_mod.__file__)), "..", "templates"
            )
            with open(os.path.join(tpl_dir, "preview_template.html.j2"), encoding="utf-8") as fh:
                template_source = fh.read()

            env = Environment(autoescape=select_autoescape(default=True, default_for_string=True))

            def stringify(a: Any) -> str:
                if isinstance(a, list):
                    return ", ".join(str(x) for x in a)
                if isinstance(a, str):
                    return a
                jsonld = getattr(a, "_jsonld", None)
                if jsonld and jsonld.get("name"):
                    return str(jsonld["name"])
                return str(a)

            def is_object_list(a: Any) -> bool:
                if isinstance(a, list):
                    return any(not isinstance(obj, str) for obj in a)
                return False

            env.globals["stringify"] = stringify  # ty: ignore[invalid-assignment]
            env.globals["is_object_list"] = is_object_list  # ty: ignore[invalid-assignment]
            src = env.from_string(template_source)

            context_entities = [e._jsonld for e in self.crate.contextual_entities]
            data_entities = [e._jsonld for e in self.crate.data_entities]
            return src.render(crate=self.crate, context=context_entities, data=data_entities)

    preview = crate.add(_SafePreview(crate))
    # ro-crate-py's Preview registers itself with nothing but an @id, so the base
    # profile asks it for a human-readable name like any other entity. The graph
    # and the maturity report beside it already say what they are; this one was
    # simply never told to. No contentSize: the preview renders the crate's own
    # entity list, so its bytes are not settled until after it is generated.
    preview["name"] = f"{AUTOGENERATED_MARKER} — RO-Crate preview"
    preview["description"] = (
        "Browsable HTML rendering of this crate's metadata, generated by vitro-crate."
    )
    preview["encodingFormat"] = "text/html"


def _embed_maturity_report(crate: ROCrate, state: CrateState) -> None:
    """Embed the maturity report into the crate and register it (#85).

    Renders ``ro-crate-metadata-maturity.html`` — profile adherence (computed in-memory
    from the crate's current ``@graph``), FAIR + DSM, OECD MIT coverage, and
    reproducibility readiness — and adds it as a ``File`` + ``CreativeWork``
    ``about`` ``./`` (the HTML is the File's in-memory source, materialised by
    ``crate.write()``). Mirrors :func:`_embed_crate_graph`.
    """
    from io import StringIO

    from builder.writers.maturity_report import REPORT_FILENAME, build_maturity_html

    # Renders from state.validation (no re-validate) so export stays cheap (#85).
    # Pass the crate's current @graph so the report can fold in the provenance
    # chain + graph-topology strip drawn from real serialized entities.
    page = build_maturity_html(state, graph=crate.metadata.generate())
    crate.add(
        File(
            crate,
            StringIO(page),
            dest_path=REPORT_FILENAME,
            properties={
                "@type": ["File", "CreativeWork"],
                "name": f"{AUTOGENERATED_MARKER} — RO-Crate maturity report",
                "description": (
                    "Profile adherence, FAIR/DSM, OECD MIT coverage, and "
                    "reproducibility readiness for this crate, generated by vitro-crate."
                ),
                "encodingFormat": "text/html",
                "about": {"@id": "./"},
            },
        )
    )


# Exports already written this process, keyed by (state fingerprint, destination,
# what was asked for). Small: an agent loop re-exports the SAME crate over and
# over, so one live entry is the normal case and a couple of destinations the
# most anyone needs.
_EXPORT_MEMO: dict[tuple[str, str, bool], dict[str, Any]] = {}
_EXPORT_MEMO_MAX = 4


def _export_memo_key(
    state: CrateState,
    output_dir: Path,
    embed_report: bool,
) -> tuple[str, str, bool] | None:
    """Memo key for an export, or None when the state cannot be fingerprinted.

    Reuses ``validation_fingerprint`` — it hashes entities plus metadata, which
    is everything ``assemble_crate`` reads, and deliberately excludes the
    verdicts and timestamps that every export writes back. Anything the written
    crate could differ by busts the key; a pure output does not.
    """
    try:
        fingerprint = state.validation_fingerprint()
    except Exception:  # noqa: BLE001 — an un-fingerprintable state just re-exports
        logger.debug("State could not be fingerprinted; exporting without the memo")
        return None
    return (fingerprint, str(output_dir.resolve()), embed_report)


def _export_is_intact(output_dir: Path) -> bool:
    """Whether a previously written crate is still on disk.

    The memo says what WE did; it cannot know what happened to the directory
    afterwards. A user who deletes the output and re-runs must get their crate
    back, so the descriptor is checked before a reuse is claimed.
    """
    try:
        return (output_dir / "ro-crate-metadata.json").is_file()
    except Exception:  # noqa: BLE001 — an unreadable path is not a valid reuse
        return False


def _remember_export(key: tuple[str, str, bool] | None, result: dict[str, Any]) -> None:
    """Record a successful export, bounding the memo."""
    if key is None or not result.get("success"):
        return
    if len(_EXPORT_MEMO) >= _EXPORT_MEMO_MAX and key not in _EXPORT_MEMO:
        _EXPORT_MEMO.pop(next(iter(_EXPORT_MEMO)), None)
    _EXPORT_MEMO[key] = result


def export_crate(
    state: CrateState,
    output_path: str | None = None,
    *,
    embed_report: bool = True,
    validate: bool = True,
) -> dict[str, Any]:
    """Assemble an RO-Crate from CrateState and write it to disk (ro-crate-py).

    This is the only step that touches disk: it creates the output directory,
    assembles a `ROCrate` from the state, and writes `ro-crate-metadata.json`
    plus any payload. It also embeds the browsable preview
    (`ro-crate-preview.html`, #86) and — unless disabled — the maturity report
    (#85), whose entity explorer is how the written crate is visually explorable
    (#615). For a fast, zero-disk conformance check during the agent loop, use
    ``build_and_validate`` instead.

    Args:
        state: The current CrateState to build from.
        output_path: Path where the crate directory should be created.
            When omitted, falls back to ``state.metadata.output_path`` (the
            user-configured destination), then to
            ``sessions/<session_id>/working_crate/``.
        embed_report: Write the maturity report (ro-crate-metadata-maturity.html, #85)
            into the crate (default True). Set False to skip it.
        validate: Validate before writing, unless the recorded verdict is already
            current AND covers every severity tier (default True). The export
            embeds a maturity report whose verdict comes from
            ``state.validation``; without this, a crate edited after its last
            validation ships a report describing a state nobody checked. The
            sweep runs at the widest gate so REQUIRED, RECOMMENDED and OPTIONAL
            are all assessed. A failing validation does NOT block the write —
            the crate is still written and the report states the real verdict.

    Returns:
        A dict with keys:
            success (bool): Whether the crate was built successfully.
            crate_path (str): The output path used (can be passed directly
                to :func:`validate`).
            error (str | None): Error message if success is False.
            validation (dict): ``{"ran", "reason", "ok", "error", "severity",
                "issue_counts"}`` from the pre-write freshness check —
                ``reason`` is ``"fresh"`` (skipped, the recorded verdict still
                describes this crate and covers every tier),
                ``"tiers-incomplete"``, ``"never-validated"`` or ``"stale"``.
                ``ok`` is REQUIRED conformance; RECOMMENDED/OPTIONAL findings
                appear in ``issue_counts`` and never mark the export not-ok.
                Absent when ``validate=False``.
    """
    try:
        if not output_path:
            # Honor the user-configured destination (set from the CLI --output /
            # state.metadata.output_path) before falling back to the session dir.
            output_path = state.metadata.output_path or _default_crate_path(state)

        output_dir = Path(output_path)
        # An export nobody's changes have reached is the same export. One
        # profiled session called this 32 times — 29 of them immediately after a
        # validate — and spent 279s of its 305s export budget rewriting a crate
        # byte for byte. `build_and_validate` already builds in memory and
        # touches no disk, so exporting to check a verdict is pure waste.
        #
        # A memo rather than a prompt rule, because it does not depend on the
        # agent behaving; and keyed on the destination too, since the same state
        # written to a second directory is a genuinely different result.
        memo_key = _export_memo_key(state, output_dir, embed_report)
        if memo_key is not None and (cached := _EXPORT_MEMO.get(memo_key)) is not None:
            if _export_is_intact(output_dir):
                logger.info("Crate already exported and unchanged: %s", output_dir)
                return {**cached, "reused": True}
            # Someone removed or emptied it since; fall through and write again.
            _EXPORT_MEMO.pop(memo_key, None)

        output_dir.mkdir(parents=True, exist_ok=True)

        # Validate BEFORE assembling, so the maturity report embedded below
        # reports on the crate actually being written. Runs the FULL severity
        # gate ("optional" covers REQUIRED + RECOMMENDED + OPTIONAL): the report
        # has a row for each tier, and a REQUIRED-only sweep left two of the
        # three reading "not assessed" in the finished crate. Skipped only when
        # the recorded verdict both matches the state and already covers every
        # tier. Never blocks the write: the report tells the truth.
        validation_info: dict[str, Any] | None = None
        if validate:
            from builder.tools.validation import ensure_validated

            validation_info = ensure_validated(state, severity="optional")
            if validation_info["error"]:
                logger.warning(
                    "Export-time validation did not complete (%s); the maturity "
                    "report will mark the verdict unverified",
                    validation_info["error"],
                )

        # Wire domain entities that nothing references onto the process that used
        # them (#438/#273). A compound reaches the experiment only through the
        # Exposure's `chemicals` field, and neither build arm guarantees that is
        # set — a real 22-compound crate exported with `chemicals=None` on every
        # process, leaving all 22 orphaned. One Exposure and N unreferenced
        # compounds have exactly one sensible wiring, so it is done rather than
        # asked; genuinely ambiguous cases are refused and reported, not guessed.
        try:
            from builder.tools.composites import wire_unreferenced_domain_entities

            wiring = wire_unreferenced_domain_entities(state)
            if wiring["wired"]:
                logger.info("Wired unreferenced domain entities: %s", wiring["wired"])
            if wiring["ambiguous"]:
                logger.warning("Domain wiring needs a human: %s", wiring["ambiguous"])
        except Exception as wire_err:  # noqa: BLE001 — wiring never fails an export
            logger.warning("Could not wire unreferenced domain entities: %s", wire_err)
            wiring = {"wired": {}, "ambiguous": []}

        # Stamp what produced this crate — application, version, model, and the
        # run's tokens/cost/wall-clock — immediately before assembly, so the
        # figures cover the whole session up to this write (#generator).
        try:
            state.stamp_generator()
        except Exception as gen_err:  # noqa: BLE001 — provenance never fails an export
            logger.warning("Could not record generator provenance: %s", gen_err)

        crate = assemble_crate(state, output_dir, materialize_payload=True)

        # Answer the one REQUIRED question the in-memory gate cannot: does the
        # crate carry the files it describes (#530)? `ensure_validated` above
        # validates a document, where a payload check has nothing to look at and
        # so emits nothing — and silence there was being read as a pass, shipping
        # a crate that fails the base profile on disk under a green "Conformant".
        # Runs here because the maturity report is rendered from `state.validation`
        # a few lines below, while the crate is still in memory: a verdict reached
        # after `crate.write()` could never reach the report that ships inside it.
        try:
            from builder.tools.validation import record_payload_check

            record_payload_check(state, crate)
        except Exception as payload_err:  # noqa: BLE001 — never fail the write
            logger.warning("Could not verify the crate payload: %s", payload_err)

        # Answer the one REQUIRED question the ISA profile cannot ask of itself:
        # does its backbone actually reach the entities the crate mints (#537)?
        # Its rules target a class inferred from the very edge whose absence is
        # the defect, so a detached process is skipped rather than failed and the
        # silence ships as a pass. Runs here for the same reason as the payload
        # check above: the report is rendered from `state.validation` below.
        try:
            from builder.tools.validation import record_isa_reachability_check

            record_isa_reachability_check(state, crate)
        except Exception as reach_err:  # noqa: BLE001 — never fail the write
            logger.warning("Could not verify the ISA backbone's reachability: %s", reach_err)

        # Embed the standard ro-crate-py preview (ro-crate-preview.html, a
        # CreativeWork about ./) so the written crate is browsable without
        # tooling (#86) — rendered through an autoescaping template so
        # crate-controlled strings can't inject script (XSS, #169).
        _add_safe_preview(crate)

        # Embed the maturity report (ro-crate-metadata-maturity.html, a CreativeWork about
        # ./, #85). Best-effort: a reporting failure must not fail the export.
        if embed_report:
            try:
                _embed_maturity_report(crate, state)
            except Exception as report_err:  # noqa: BLE001 — never fail export on the report
                logger.warning("Could not embed maturity report: %s", report_err)

        crate.write(str(output_dir))

        # Remember where it landed: without this the state cannot say where the
        # crate went, so the goodbye summary (and a later re-export) had to guess
        # the default even when the caller named a different destination.
        state.metadata.output_path = output_path
        state.metadata.exported_at = _config.now().isoformat()

        logger.info("Crate exported to %s", output_path)
        out: dict[str, Any] = {"success": True, "crate_path": output_path, "error": None}
        if validation_info is not None:
            out["validation"] = validation_info
        # A step whose output the deposit did not contain used to be reported
        # here, because the build had written an empty stand-in for it. Nothing
        # is written now (#592): the step is left without a `schema:result` and
        # the tox Violation carries the gap through validation, where the agent
        # and the maturity report both already read it. Reporting it twice, from
        # a second source that could drift, is what this key was.
        if wiring["wired"] or wiring["ambiguous"]:
            out["wiring"] = wiring
        # Remembered AFTER the write, and only on success, so a failed export is
        # never reported as a completed one on the next call.
        _remember_export(memo_key, out)
        return out

    except OSError as e:
        logger.error("Failed to create crate at %s: %s", output_path, e)
        return {"success": False, "crate_path": output_path, "error": str(e)}
    except Exception as e:
        logger.error("Unexpected error building crate: %s", e)
        return {"success": False, "crate_path": output_path, "error": str(e)}


def build_crate(state: CrateState, output_path: str | None = None) -> dict[str, Any]:
    """Back-compat alias for :func:`export_crate` (the on-disk writer)."""
    return export_crate(state, output_path)


