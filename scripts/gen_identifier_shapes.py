#!/usr/bin/env python3
"""Generate ``profiles/shapes/tox/14_identifier_namespaces.ttl``.

The ISA-Tox shapes that check the *form* of an identifier are not written by hand.
Which namespaces are checked is a table (``NAMESPACE_CHECKS`` and ``VALUE_CHECKS``
in ``profiles/identifier_namespaces.py``); what a well-formed identifier looks like
in each is the Bioregistry's record, vendored in
``profiles/vocabulary/identifier_namespaces.json``. This script joins the two.

One shape per question, not one per namespace:

* ``tox:PersonMustBeIdentifiedByOrcid`` and ``tox:OrganizationMustBeIdentifiedByRor``
  ask whether the ``@id`` is in the namespace at all, and
  ``tox:FunderShouldBeIdentifiedByRor`` asks it, as a recommendation, of an
  Organization the crate names only as a funder: a funding programme often has no
  ROR record to give.
* ``tox:IdentifierMustBeWellFormed`` asks whether an ``@id`` in any checked
  namespace has that namespace's form: an ``sh:or`` with one member per namespace,
  each a pattern beside the record it was derived from.
* ``tox:IdentifierValueMustBeWellFormed`` asks the same of the ``value`` of an
  identifier PropertyValue, one member per scheme name.
* ``tox:MolecularEntityInChIKeyMustBeWellFormed`` asks it of an InChIKey.

The members are plain ``sh:pattern`` constraints on purpose. A SPARQL constraint
with a branch per namespace says the same thing and is re-parsed and run once per
entity: 113 s on a 365-entity crate against 3 s for this form.

Every constraint has its message and severity on the node shape: both engines
ignore a severity inside a constraint. The funder shape is the one Warning, and a
node shape below Violation is not loaded under the REQUIRED gate, which is what a
recommendation means.

Regenerate with::

    uv run python scripts/gen_identifier_shapes.py

``--check`` writes nothing and fails when the committed file differs, which is
what ``tests/test_identifier_namespace_shapes.py`` runs.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

_REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_REPO))

from profiles import identifier_namespaces as ns  # noqa: E402

OUTPUT = _REPO / "profiles" / "shapes" / "tox" / "14_identifier_namespaces.ttl"

_HEADER = """\
# SPDX-License-Identifier: MIT
# GENERATED by scripts/gen_identifier_shapes.py. Do not edit: change the tables in
# profiles/identifier_namespaces.py, then run the script.
#
# Identifier namespaces: an identifier MUST have the form its registry gives it.
# Every Person is identified by an ORCID iD and every Organization by a ROR ID, an
# Organization named only as a funder SHOULD be (a programme often has none), and
# any other identifier is checked only where the crate claims its namespace. Each
# sh:pattern is derived from the record the rdfs:seeAlso beside it names: the
# Bioregistry's, vendored in profiles/vocabulary/identifier_namespaces.json. An
# identifier is a fact about what it identifies, so none may be invented to
# satisfy these shapes.

@prefix bioschemas: <https://bioschemas.org/> .
@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .
@prefix schema: <http://schema.org/> .
@prefix sh: <http://www.w3.org/ns/shacl#> .
@prefix tox: <https://w3id.org/ro/crate/isa-tox/1.0/> .
"""


def _ttl(text: str) -> str:
    """*text* inside a Turtle string literal."""
    return text.replace("\\", "\\\\").replace('"', '\\"')


def _sparql(text: str) -> str:
    """*text* inside a SPARQL string literal (which the Turtle literal then holds)."""
    return text.replace("\\", "\\\\").replace('"', '\\"')


def _record(prefix: str) -> str:
    return ns.record(prefix)["record"]


def _agent_shape(
    shape: str,
    name: str,
    description: str,
    prefix: str,
    message: str,
    *,
    cls: str | None = None,
    select: str | None = None,
    severity: str = "Violation",
) -> str:
    """A shape asking whether an @id is in *prefix*'s namespace at all."""
    if select is not None:
        target = f'''sh:target [
        a sh:SPARQLTarget ;
        sh:select """{_ttl(select)}""" ;
    ] ;'''
    else:
        target = f"sh:targetClass schema:{cls} ;"
    return f"""
tox:{shape} a sh:NodeShape ;
    sh:name "{name}" ;
    sh:description "{description}" ;
    {target}
    rdfs:seeAlso <{_record(prefix)}> ;
    sh:pattern "{_ttl(ns.namespace_pattern(prefix))}" ;
    sh:message "{message}" ;
    sh:severity sh:{severity} .
"""


# An Organization the crate names only as a funder: nothing refers to it but a
# `funder` (or its super-property `sponsor`, which an engine that infers
# sub-properties adds beside it). Such an organisation is often a funding
# programme ROR has no record for and never will, so a missing ROR ID there is a
# recommendation; everywhere else it is required. The node itself is excluded as a
# referrer, since OWL RL states every node `owl:sameAs` itself.
_FUNDING_LINKS = "<http://schema.org/funder>, <http://schema.org/sponsor>"
_ONLY_A_FUNDER = f"""
                ?funded <http://schema.org/funder> ?this .
                FILTER NOT EXISTS {{
                    ?other ?link ?this .
                    FILTER (?other != ?this && ?link NOT IN ({_FUNDING_LINKS}))
                }}"""
_ORGANIZATIONS = """
            SELECT DISTINCT ?this WHERE {{
                ?this a <http://schema.org/Organization> .{condition}
            }}
        """


def _organizations(condition: str) -> str:
    return _ORGANIZATIONS.format(condition=condition)


_NOT_ONLY_A_FUNDER = f"""
                FILTER (
                    NOT EXISTS {{ ?funded <http://schema.org/funder> ?this }}
                    || EXISTS {{
                        ?other ?link ?this .
                        FILTER (?other != ?this && ?link NOT IN ({_FUNDING_LINKS}))
                    }}
                )"""


_NAMESPACE_DESCRIPTION = (
    "An entity whose @id is in a registered identifier namespace MUST have the form "
    "the registry gives that namespace."
)
_VALUE_DESCRIPTION = (
    "The value of a PropertyValue named after an identifier scheme MUST have the form "
    "the registry gives that scheme."
)


def _namespace_shape() -> str:
    starts = "|".join(ns.escape(ns.namespace_start(p)) for p in ns.NAMESPACE_CHECKS)
    members = "\n".join(
        f"        # {ns.record(p)['name']}: {ns.example_iri(p)}\n"
        f"        [ rdfs:seeAlso <{_record(p)}> ;\n"
        f'          sh:pattern "{_ttl(ns.iri_pattern(p))}" ]'
        for p in ns.NAMESPACE_CHECKS
    )
    return f"""
# Selected: every described entity whose @id starts with one of the namespaces
# below. The whole prefix is matched, so an ontology's own IRI (…/obo/ncit.owl) and
# the scheme a PropertyValue names (https://orcid.org) are not identifiers here.
tox:IdentifierMustBeWellFormed a sh:NodeShape ;
    sh:name "An identifier MUST be well-formed in its namespace" ;
    sh:description "{_NAMESPACE_DESCRIPTION}" ;
    sh:target [
        a sh:SPARQLTarget ;
        sh:select \"\"\"
            SELECT DISTINCT ?this WHERE {{
                ?this a ?type .
                FILTER(isIRI(?this) && REGEX(STR(?this), "{_ttl(_sparql("^(" + starts + ")"))}"))
            }}
        \"\"\" ;
    ] ;
    sh:or (
{members}
    ) ;
    sh:message "An @id in a registered identifier namespace {ns.MALFORMED}" ;
    sh:severity sh:Violation .
"""


def _value_shape() -> str:
    names = ", ".join(f'"{_ttl(_sparql(name))}"' for name in ns.VALUE_CHECKS)
    members = "\n".join(
        f"        # {ns.record(p)['name']}: {ns.record(p)['example']}\n"
        f'        [ sh:property [ sh:path schema:name ; sh:hasValue "{_ttl(name)}" ] ;\n'
        f"          sh:property [ sh:path schema:value ;\n"
        f"                        rdfs:seeAlso <{_record(p)}> ;\n"
        f'                        sh:pattern "{_ttl(ns.value_pattern(p))}" ] ]'
        for name, p in ns.VALUE_CHECKS.items()
    )
    return f"""
# Selected: the identifier PropertyValues, by the name that states their scheme.
# Each member is one scheme: that name, and the form of its value.
tox:IdentifierValueMustBeWellFormed a sh:NodeShape ;
    sh:name "An identifier value MUST be well-formed in its scheme" ;
    sh:description "{_VALUE_DESCRIPTION}" ;
    sh:target [
        a sh:SPARQLTarget ;
        sh:select \"\"\"
            SELECT DISTINCT ?this WHERE {{
                ?this a <http://schema.org/PropertyValue> .
                ?this <http://schema.org/name> ?name .
                FILTER(?name IN ({names}))
            }}
        \"\"\" ;
    ] ;
    sh:or (
{members}
    ) ;
    sh:message "An identifier PropertyValue's schema:value {ns.MALFORMED}" ;
    sh:severity sh:Violation .
"""


def _inchikey_shape() -> str:
    return f"""
tox:MolecularEntityInChIKeyMustBeWellFormed a sh:NodeShape ;
    sh:name "A chemical's InChIKey MUST be well-formed" ;
    sh:description "An InChIKey a chemical states MUST have the form its registry gives it." ;
    sh:targetClass bioschemas:MolecularEntity ;
    sh:property [
        a sh:PropertyShape ;
        sh:path schema:inChIKey ;
        rdfs:seeAlso <{_record("inchikey")}> ;
        sh:pattern "{_ttl(ns.value_pattern("inchikey"))}" ;
        sh:message "A MolecularEntity's schema:inChIKey {ns.MALFORMED}" ;
        sh:severity sh:Violation ;
    ] .
"""


def render() -> str:
    """The whole file, as a string."""
    return "".join(
        (
            _HEADER,
            _agent_shape(
                "PersonMustBeIdentifiedByOrcid",
                "A person MUST be identified by an ORCID iD",
                "A Person's @id MUST be the address of the person's ORCID iD.",
                "orcid",
                f"A Person {ns.PERSON_NEEDS_ORCID}: its @id is "
                f"{ns.uri_prefix('orcid')} followed by the iD",
                cls="Person",
            ),
            _agent_shape(
                "OrganizationMustBeIdentifiedByRor",
                "An organization MUST be identified by a ROR ID",
                "An Organization's @id MUST be the address of the organization's ROR ID, "
                "unless the crate names it only as a funder.",
                "ror",
                f"An Organization {ns.ORGANIZATION_NEEDS_ROR}: its @id is "
                f"{ns.uri_prefix('ror')} followed by the ID",
                select=_organizations(_NOT_ONLY_A_FUNDER),
            ),
            _agent_shape(
                "FunderShouldBeIdentifiedByRor",
                "A funder SHOULD be identified by a ROR ID",
                "An Organization the crate names only as a funder SHOULD be identified by "
                "a ROR ID. A funding programme often has none.",
                "ror",
                f"An Organization named only as a funder {ns.FUNDER_SHOULD_HAVE_ROR}: its "
                f"@id is {ns.uri_prefix('ror')} followed by the ID",
                select=_organizations(_ONLY_A_FUNDER),
                severity="Warning",
            ),
            _namespace_shape(),
            _value_shape(),
            _inchikey_shape(),
        )
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="write nothing; fail when the committed file differs from the output",
    )
    args = parser.parse_args()
    rendered = render()
    name = OUTPUT.relative_to(_REPO)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != rendered:
            print(f"{name} is not what this script generates; run it without --check")
            return 1
        print(f"{name} is up to date")
        return 0
    OUTPUT.write_text(rendered, encoding="utf-8")
    print(
        f"wrote {name}: {len(ns.NAMESPACE_CHECKS)} namespaces, "
        f"{len(ns.VALUE_CHECKS)} identifier values"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
